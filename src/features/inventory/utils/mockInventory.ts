export function cloneInventoryData(
  data: OrganizationInventoryData,
): OrganizationInventoryData {
  return {
    organizationId: data.organizationId,
    branchId: data.branchId,
    branchName: data.branchName,
    storageRevision: data.storageRevision,
    lastSequence: data.lastSequence,
    balances: data.balances.map((bal) => ({ ...bal })),
    movements: data.movements.map((mov) => ({ ...mov })),
  }
}

