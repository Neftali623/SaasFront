export function getBranchForOrganization(
  organizationId: string,
  fallbackBranchName = 'Sucursal Principal',
): BranchInfo {
  const configured = DEFAULT_BRANCH_BY_ORG[organizationId]
  if (configured) {
    return configured
  }
  return {
    id: `branch-${organizationId}-main`,
    organizationId,
    name: fallbackBranchName,
  }
}

