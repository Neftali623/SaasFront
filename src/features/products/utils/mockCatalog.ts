export function cloneCatalogData(
  catalog: OrganizationCatalogData,
): OrganizationCatalogData {
  return {
    baseCurrency: catalog.baseCurrency ?? 'MXN',
    categories: catalog.categories.map((cat) => ({ ...cat })),
    products: catalog.products.map((prod) => ({
      ...prod,
      barcodes: [...prod.barcodes],
    })),
  }
}

