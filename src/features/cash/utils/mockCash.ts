export function getRegisterForOrganization(
  organizationId: string,
  fallbackBranchName = 'Sucursal Principal',
): CashRegister {
  const configured = DEFAULT_REGISTER_BY_ORG[organizationId]
  if (configured) {
    return { ...configured }
  }
  const branch = getBranchForOrganization(organizationId, fallbackBranchName)
  return {
    id: `reg-${organizationId}-01`,
    organizationId,
    branchId: branch.id,
    branchName: branch.name,
    name: 'Caja 01 - Principal',
    code: 'CAJA-01',
  }
}

